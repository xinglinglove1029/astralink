import { spawn } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { existsSync } from 'node:fs';
const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cargoBin = join(process.env.USERPROFILE || process.env.HOME || '', '.cargo', 'bin');
const env = { ...process.env };
const pathKey = Object.keys(env).find(key => key.toLowerCase() === 'path');
const originalPath = pathKey ? env[pathKey] : '';
for (const key of Object.keys(env)) if (key.toLowerCase() === 'path') delete env[key];
const paths = [existsSync(cargoBin) ? cargoBin : '', dirname(process.execPath), originalPath].filter(Boolean);
env[process.platform === 'win32' ? 'Path' : 'PATH'] = paths.join(process.platform === 'win32' ? ';' : ':');
const cli = join(project, 'node_modules', '@tauri-apps', 'cli', 'tauri.js');
const args = process.argv.slice(2);
if (!args.length) args.push('dev');
const child = spawn(process.execPath, [cli, ...args], { cwd: project, env, stdio: 'inherit', windowsHide: true });
child.on('error', error => { console.error(error.message); process.exitCode = 1; });
child.on('exit', code => { process.exitCode = code || 0; });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
