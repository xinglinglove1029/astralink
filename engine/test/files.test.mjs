import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, symlink, rm } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { feature, profile, tokens, request, fakeSsh } from './helpers.mjs';
test('upstream SFTP tool calls preserve write, append, paged read, upload, download and binary errors', async (t) => {
  const ssh = await fakeSsh({ password: 'sftp-pass', sftp: true });
  t.after(() => ssh.close());
  const { createEngine } = await feature('engine');
  const engine = await createEngine({ ...tokens, port: 0 });
  t.after(() => engine.close());
  const p = profile({ port: ssh.port, password: 'sftp-pass', tryKeyboard: false });
  await request(engine, '/control/profiles', { profiles: [p] });
  const client = new Client({ name: 'sftp integration', version: '1.0' });
  await client.connect(new StreamableHTTPClientTransport(new URL(engine.url + '/mcp'), { requestInit: { headers: { authorization: 'Bearer ' + tokens.mcpToken } } }));
  t.after(() => client.close());
  const call = async (name, args) => {
    const result = await client.callTool({ name, arguments: { connectionName: 'test', ...args } });
    assert.ok(!result.isError, JSON.stringify(result));
    return result.content[0].text;
  };
  assert.match(await call('write-file', { remotePath: '/demo', content: "line one\n'quoted'\n", mode: 420 }), /Wrote/);
  assert.match(await call('write-file', { remotePath: '/demo', content: 'tail', append: true }), /Appended/);
  const paged = await call('read-file', { remotePath: '/demo', offset: 5, length: 6 });
  assert.match(paged, /one/);
  assert.match(paged, /next offset/i);
  const local = fileURLToPath(new URL('./helpers.mjs', import.meta.url));
  assert.match(await call('upload', { localPath: local, remotePath: '/uploaded' }), /uploaded/i);
  const temp = await mkdtemp(fileURLToPath(new URL('./.transfer-', import.meta.url)));
  t.after(() => rm(temp, { recursive: true, force: true }));
  const downloaded = path.join(temp, 'downloaded.txt');
  await call('download', { remotePath: '/uploaded', localPath: downloaded });
  assert.deepEqual(await readFile(downloaded), await readFile(local));
  const binary = await client.callTool({ name: 'read-file', arguments: { remotePath: '/binary', connectionName: 'test' } });
  assert.equal(binary.isError, true);
  assert.match(binary.content[0].text, /binary/i);
  assert.deepEqual(ssh.seen.commands, []);
});
test('explicit external local root enables deployment transfers and rejects unapproved and escaped paths', async (t) => {
  const base = await mkdtemp(path.join(tmpdir(), 'astralink-allowlist-'));
  t.after(() => rm(base, { recursive: true, force: true }));
  const approved = path.join(base, 'approved'), unapproved = path.join(base, 'unapproved');
  await mkdir(approved);
  await mkdir(unapproved);
  const approvedFile = path.join(approved, 'artifact.txt'), rejectedFile = path.join(unapproved, 'artifact.txt');
  await writeFile(approvedFile, 'deployment artifact');
  await writeFile(rejectedFile, 'unapproved artifact');
  const relative = path.relative(process.cwd(), approved);
  assert.ok(relative.startsWith('..') || path.isAbsolute(relative));
  const ssh = await fakeSsh({ password: 'artifact-pass', sftp: true });
  t.after(() => ssh.close());
  const { createEngine } = await feature('engine');
  const engine = await createEngine({ ...tokens, port: 0 });
  t.after(() => engine.close());
  const p = profile({ port: ssh.port, password: 'artifact-pass', tryKeyboard: false });
  await request(engine, '/control/profiles', { profiles: [p] });
  const client = new Client({ name: 'allowlist test', version: '1' });
  await client.connect(new StreamableHTTPClientTransport(new URL(engine.url + '/mcp'), { requestInit: { headers: { authorization: 'Bearer ' + tokens.mcpToken } } }));
  t.after(() => client.close());
  const call = (name, args) => client.callTool({ name, arguments: { connectionName: p.name, ...args } });
  const defaultDenied = await call('upload', { localPath: approvedFile, remotePath: '/deploy/default-denied' });
  assert.equal(defaultDenied.isError, true);
  assert.match(defaultDenied.content[0].text, /LOCAL_PATH_NOT_ALLOWED/);
  const configured = { ...p, allowedLocalPaths: [approved], allowedRemotePaths: ['/deploy'] };
  assert.equal((await request(engine, '/control/profiles', { profiles: [configured] })).status, 200);
  assert.deepEqual(engine.pool.profiles.get(p.id).allowedLocalPaths, [approved]);
  const uploaded = await call('upload', { localPath: approvedFile, remotePath: '/deploy/artifact.txt' });
  assert.ok(!uploaded.isError, JSON.stringify(uploaded));
  const remote = await call('read-file', { remotePath: '/deploy/artifact.txt' });
  assert.match(remote.content[0].text, /deployment artifact/);
  const downloaded = path.join(approved, 'downloaded.txt');
  assert.ok(!(await call('download', { remotePath: '/deploy/artifact.txt', localPath: downloaded })).isError);
  assert.equal(await readFile(downloaded, 'utf8'), 'deployment artifact');
  for (const localPath of [rejectedFile, path.join(approved, '..', 'unapproved', 'artifact.txt')]) {
    const denied = await call('upload', { localPath, remotePath: '/deploy/denied' });
    assert.equal(denied.isError, true);
    assert.match(denied.content[0].text, /LOCAL_PATH_NOT_ALLOWED/);
  }
  const link = path.join(approved, 'escape');
  await symlink(unapproved, link, process.platform === 'win32' ? 'junction' : 'dir');
  const escaped = await call('upload', { localPath: path.join(link, 'artifact.txt'), remotePath: '/deploy/escaped' });
  assert.equal(escaped.isError, true);
  assert.match(escaped.content[0].text, /LOCAL_PATH_NOT_ALLOWED/);
  for (const remotePath of ['/unapproved/artifact', '/deploy-other/artifact', '/deploy/../escape']) {
    const denied = await call('upload', { localPath: approvedFile, remotePath });
    assert.equal(denied.isError, true);
    assert.match(denied.content[0].text, /REMOTE_PATH_NOT_ALLOWED/);
  }
  const before = engine.pool.entries.get(p.name);
  assert.equal((await request(engine, '/control/profiles', { profiles: [{ ...configured, allowedLocalPaths: ['relative'] }] })).status, 400);
  assert.equal(engine.pool.entries.get(p.name), before);
});
